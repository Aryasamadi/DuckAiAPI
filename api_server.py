#!/usr/bin/env python3
"""OpenAI-compatible authenticated proxy for a configured upstream API.

The public API token authenticates clients to this proxy. The upstream API key
is kept server-side and is never returned to clients or included in responses.
"""
from __future__ import annotations

import hmac
import json
import os
from typing import Any, AsyncIterator
from urllib.parse import urlsplit

import httpx
from fastapi import Depends, FastAPI, Header, HTTPException, Request
from fastapi.responses import Response, StreamingResponse

app = FastAPI(title="OpenAI-Compatible Upstream Proxy", version="1.0.0")


def require_api_token(
    authorization: str | None = Header(default=None),
    x_api_key: str | None = Header(default=None, alias="X-API-Key"),
) -> None:
    expected = os.environ.get("DUCKAI_API_TOKEN", "")
    if not expected:
        raise HTTPException(status_code=503, detail="Proxy client token is not configured")

    supplied = x_api_key or ""
    if authorization and authorization.lower().startswith("bearer "):
        supplied = authorization[7:].strip()
    if not supplied or not hmac.compare_digest(supplied, expected):
        raise HTTPException(status_code=401, detail="Invalid or missing API token")


def upstream_config() -> tuple[str, str]:
    base_url = os.environ.get("UPSTREAM_BASE_URL", "").strip().rstrip("/")
    api_key = os.environ.get("UPSTREAM_API_KEY", "").strip()
    if not base_url or not api_key:
        raise HTTPException(
            status_code=503,
            detail="Upstream is not configured. Set UPSTREAM_BASE_URL and UPSTREAM_API_KEY.",
        )

    parsed = urlsplit(base_url)
    if (
        parsed.scheme != "https"
        or not parsed.hostname
        or parsed.username is not None
        or parsed.password is not None
        or parsed.query
        or parsed.fragment
    ):
        raise HTTPException(
            status_code=500,
            detail="UPSTREAM_BASE_URL must be an HTTPS API base URL without credentials, query, or fragment.",
        )
    return base_url, api_key


def make_http_client(streaming: bool = False) -> httpx.AsyncClient:
    timeout = httpx.Timeout(
        connect=20.0,
        read=None if streaming else 180.0,
        write=60.0,
        pool=20.0,
    )
    return httpx.AsyncClient(timeout=timeout, follow_redirects=False)


def safe_response_headers(upstream: httpx.Response) -> dict[str, str]:
    # Hop-by-hop and body-framing headers must be generated by this server.
    blocked = {
        "connection",
        "keep-alive",
        "proxy-authenticate",
        "proxy-authorization",
        "te",
        "trailer",
        "transfer-encoding",
        "upgrade",
        "content-length",
        "content-encoding",
        "set-cookie",
    }
    return {key: value for key, value in upstream.headers.items() if key.lower() not in blocked}


async def close_after_stream(
    upstream: httpx.Response, client: httpx.AsyncClient
) -> AsyncIterator[bytes]:
    try:
        async for chunk in upstream.aiter_bytes():
            if chunk:
                yield chunk
    finally:
        await upstream.aclose()
        await client.aclose()


async def forward(
    method: str,
    endpoint: str,
    request: Request,
    *,
    body: bytes | None = None,
    streaming: bool = False,
) -> tuple[httpx.AsyncClient, httpx.Response]:
    base_url, upstream_key = upstream_config()
    target_url = f"{base_url}/{endpoint.lstrip('/')}"
    headers = {
        "Authorization": f"Bearer {upstream_key}",
        "Accept": request.headers.get("accept", "application/json"),
    }
    if body is not None:
        headers["Content-Type"] = request.headers.get("content-type", "application/json")

    client = make_http_client(streaming=streaming)
    try:
        outgoing = client.build_request(
            method,
            target_url,
            params=request.query_params,
            headers=headers,
            content=body,
        )
        response = await client.send(outgoing, stream=True)
        return client, response
    except httpx.RequestError as exc:
        await client.aclose()
        # Do not expose request details; they can contain provider URLs or credentials.
        raise HTTPException(status_code=502, detail="Could not reach the configured upstream API") from exc


@app.get("/health")
def health() -> dict[str, Any]:
    configured = bool(
        os.environ.get("UPSTREAM_BASE_URL", "").strip()
        and os.environ.get("UPSTREAM_API_KEY", "").strip()
        and os.environ.get("DUCKAI_API_TOKEN", "").strip()
    )
    return {"status": "ok", "mode": "openai-proxy", "upstream_configured": configured}


@app.get("/v1/models", dependencies=[Depends(require_api_token)])
async def list_models(request: Request) -> Response:
    client, upstream = await forward("GET", "models", request)
    try:
        content = await upstream.aread()
        return Response(
            content=content,
            status_code=upstream.status_code,
            headers=safe_response_headers(upstream),
        )
    finally:
        await upstream.aclose()
        await client.aclose()


@app.post("/v1/chat/completions", dependencies=[Depends(require_api_token)])
async def chat_completions(request: Request) -> Response:
    raw_body = await request.body()
    try:
        payload = json.loads(raw_body)
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise HTTPException(status_code=400, detail="Request body must be valid JSON") from exc
    if not isinstance(payload, dict):
        raise HTTPException(status_code=400, detail="Request body must be a JSON object")

    streaming = payload.get("stream") is True
    client, upstream = await forward(
        "POST",
        "chat/completions",
        request,
        body=raw_body,
        streaming=streaming,
    )
    headers = safe_response_headers(upstream)
    if streaming:
        return StreamingResponse(
            close_after_stream(upstream, client),
            status_code=upstream.status_code,
            headers=headers,
            media_type=upstream.headers.get("content-type"),
        )

    try:
        content = await upstream.aread()
        return Response(
            content=content,
            status_code=upstream.status_code,
            headers=headers,
        )
    finally:
        await upstream.aclose()
        await client.aclose()
